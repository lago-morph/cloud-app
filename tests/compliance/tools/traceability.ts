/**
 * Traceability report (COMPL-REQ-002): every `*-AC-*` and `E2E-*` ID defined in the documents,
 * with the tests tagged with it and its latest recorded result per target; IDs with no tagged
 * test are flagged untested, and tags naming no defined ID are flagged too.
 *
 * Release 1 judges local and Cloudflare only (DEC-0508): results are shown for those targets, and
 * a criterion that applies only on AWS is listed as deferred (branch `aws`), never as untested.
 */
import type { EvidenceRecord } from "../../../packages/framework/src/evidence/public.js";
import { parseTags } from "../../support/tags.js";
import { DEFERRED, isDeferred, RELEASE_TARGETS, selectedEntries, type CatalogueEntry, type ReleaseTarget } from "../harness/catalogue.js";
import { isDryRun } from "./records.js";

export interface ListedTest {
  /** Full title including describe titles. */
  readonly title: string;
  /** Repository-relative path. */
  readonly file: string;
}

export interface TraceRow {
  readonly id: string;
  readonly where: string;
  readonly source: string;
  readonly tests: readonly string[];
  /** Latest recorded result per release target, as text. */
  readonly results: Partial<Record<ReleaseTarget, string>>;
  readonly untested: boolean;
  /** Applies on no release target (an AWS-only criterion): deferred with the AWS target, never untested. */
  readonly deferred: boolean;
}

export interface TraceabilityReport {
  readonly rows: readonly TraceRow[];
  readonly untested: readonly string[];
  readonly deferred: readonly string[];
  readonly unknownTags: readonly string[];
}

const TAG_CALL = /\btag\(\s*(\[[^\]]*\]|"[^"]*"|'[^']*')/g;
const QUOTED_ID = /["']((?:[A-Z]+-AC|E2E)-\d{3})["']/g;
const BRACKETED = /\[((?:[A-Z]+-AC|E2E)-\d{3})\]/g;

/**
 * IDs a test source file tags tests with: bracketed `[ID]` titles and `tag("ID", …)` /
 * `tag(["ID", …], …)` calls. Used next to the runners' listings, for titles a listing cannot
 * produce (suites defined after a dynamic import).
 */
export function scanSourceTags(source: string): string[] {
  const ids = new Set<string>();
  for (const m of source.matchAll(BRACKETED)) if (m[1] !== undefined) ids.add(m[1]);
  for (const call of source.matchAll(TAG_CALL)) {
    for (const m of (call[1] ?? "").matchAll(QUOTED_ID)) if (m[1] !== undefined) ids.add(m[1]);
  }
  return [...ids].sort();
}

/** Undefined when the record has no entry for the ID other than the not-selected one (DEC-0265). */
function describeResults(record: EvidenceRecord, id: string): string | undefined {
  const entries = selectedEntries(record, id);
  if (entries.length === 0) return undefined;
  const text = entries.map((r) => (r.detail === undefined ? r.status : `${r.status}: ${r.detail}`)).join("; ");
  return `${text} (${record.finishedAt})`;
}

export function buildTraceability(input: { readonly catalogue: readonly CatalogueEntry[]; readonly tests: readonly ListedTest[]; readonly records: readonly EvidenceRecord[] }): TraceabilityReport {
  const known = new Set(input.catalogue.map((e) => e.id));
  const testsById = new Map<string, string[]>();
  const unknownTags: string[] = [];
  for (const test of input.tests) {
    const label = `${test.file} › ${test.title}`;
    for (const id of new Set(parseTags(test.title))) {
      if (!known.has(id)) unknownTags.push(`${id} (${label})`);
      testsById.set(id, [...(testsById.get(id) ?? []), label]);
    }
  }
  // A dry run's record (G-EV F3) is never evidence, so it is never shown as a result.
  const latest = input.records.filter((r) => !isDryRun(r)).sort((a, b) => (a.finishedAt < b.finishedAt ? 1 : a.finishedAt > b.finishedAt ? -1 : 0));
  const rows = input.catalogue.map((entry): TraceRow => {
    const results: Partial<Record<ReleaseTarget, string>> = {};
    for (const target of RELEASE_TARGETS) {
      for (const record of latest) {
        if (record.target !== target) continue;
        const text = describeResults(record, entry.id);
        if (text !== undefined) {
          results[target] = text;
          break;
        }
      }
    }
    const tests = testsById.get(entry.id) ?? [];
    const deferred = isDeferred(entry);
    return { id: entry.id, where: entry.where, source: entry.source, tests, results, untested: !deferred && tests.length === 0, deferred };
  });
  return { rows, untested: rows.filter((r) => r.untested).map((r) => r.id), deferred: rows.filter((r) => r.deferred).map((r) => r.id), unknownTags };
}

const cell = (text: string): string => text.split("|").join("\\|").split("\n").join(" ");

export function renderTraceability(report: TraceabilityReport): string {
  const lines = [
    "# Traceability report",
    "",
    "Generated by `tests/compliance/tools/traceability.ts` (COMPL-REQ-002) from the documents, the tagged tests and the evidence records under `validation/`. It records; the evaluator judges.",
    "",
    `Targets judged: ${RELEASE_TARGETS.join(", ")}. The AWS target is ${DEFERRED}.`,
    "",
    `Criteria and scenarios: ${String(report.rows.length)}, of which ${String(report.deferred.length)} deferred with the AWS target. Untested: ${String(report.untested.length)} of ${String(report.rows.length - report.deferred.length)}.`,
    "",
    "| ID | Where | Tests | local | cloudflare |",
    "| --- | --- | --- | --- | --- |",
  ];
  for (const row of report.rows) {
    const tests = row.deferred ? `deferred (branch \`aws\`)` : row.untested ? "**UNTESTED**" : row.tests.map(cell).join("<br>");
    lines.push(`| ${row.id} | ${cell(row.where)} | ${tests} | ${cell(row.results.local ?? "—")} | ${cell(row.results.cloudflare ?? "—")} |`);
  }
  lines.push("", "## Untested", "", ...(report.untested.length === 0 ? ["None."] : report.untested.map((id) => `- ${id}`)));
  lines.push("", "## Deferred with the AWS target (DEC-0508, branch `aws`)", "", ...(report.deferred.length === 0 ? ["None."] : [report.deferred.join(", ")]));
  lines.push("", "## Tags naming no defined criterion or scenario", "", ...(report.unknownTags.length === 0 ? ["None."] : report.unknownTags.map((t) => `- ${cell(t)}`)));
  return `${lines.join("\n")}\n`;
}
