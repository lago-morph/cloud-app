/**
 * The generated configuration module (DEC-0063, config.md §2 "Delivery"). The build writes it
 * under `.framework/` and bundles it with the target entry point, which passes its default
 * export to `createConfigService`. A running build therefore never sees later edits to the
 * values file (CFG-REQ-003). The resolved configuration holds no secret values.
 */
import type { ResolvedConfig } from "./resolve.js";

/** JavaScript module source whose default export is `resolved`, as plain JSON data. */
export function generateConfigModule(resolved: ResolvedConfig): string {
  const data = JSON.stringify(resolved, null, 2).replace(/[<\u2028\u2029]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
  return `// Generated by the framework build from the committed values file. Do not edit.\nconst config = ${data};\nexport default config;\n`;
}
