import { describe, expect, it } from "vitest";
import { createDeployment } from "../core/identity.js";
import { generateConfigModule } from "./embed.js";
import { configString, configStringList } from "./public.js";
import { resolveConfig } from "./resolve.js";
import { createConfigService } from "./service.js";

const resolved = resolveConfig({
  deployment: createDeployment({ app: "notes", stage: "test-ab12", target: "cloudflare" }),
  declaration: { title: configString(), tags: configStringList({ default: [] }) },
  secrets: ["apiKey"],
  file: "config/cloudflare/test.json",
  config: { values: { title: 'Line "one"\n</script>\u2028' }, framework: {} },
});

async function load(source: string): Promise<unknown> {
  const module = (await import(/* @vite-ignore */ `data:text/javascript;base64,${Buffer.from(source).toString("base64")}`)) as { default: unknown };
  return module.default;
}

describe("generated configuration module (DEC-0063)", () => {
  it("default-exports exactly the resolved configuration", async () => {
    expect(await load(generateConfigModule(resolved))).toEqual(JSON.parse(JSON.stringify(resolved)));
  });

  it("the runtime service reads the embedded values", async () => {
    const embedded = (await load(generateConfigModule(resolved))) as Parameters<typeof createConfigService>[0];
    expect(createConfigService(embedded).get("title")).toBe('Line "one"\n</script>\u2028');
  });

  it("is deterministic and marked as generated", () => {
    const source = generateConfigModule(resolved);
    expect(generateConfigModule(resolved)).toBe(source);
    expect(source.split("\n")[0]).toMatch(/^\/\/ Generated by the framework build/);
  });

  it("imports nothing, so it bundles for any target", () => {
    expect(generateConfigModule(resolved)).not.toMatch(/\bimport\b|\brequire\(/);
  });
});
