/**
 * CHECK-REQ-004 migration checker, run by `npx <package> verify` on fixture apps whose
 * migration histories are produced by `generate-migration` and then changed the way an
 * agent might change them by hand. Fixture layer: `test/fixtures/mig/base`.
 */
import { afterAll, describe, expect, it } from "vitest";
import { tag } from "../../../../../tests/support/tags.js";
import {
  FixtureApp,
  addHandWrittenMigration,
  editMigrationKeepingChecksum,
  migrationFiles,
  type RunResult,
} from "../../fixtures/support/app.js";

const TIMEOUT = 900_000;
const ADD_COPY_DROP = /add[\s,-]+copy[\s,-]+(?:and[\s-]+)?drop/i;
const PKG = "@lago-morph/prototype-framework";
const HELPERS = ["boolean", "defineTable", "id", "integer", "number", "text", "timestamp"] as const;

const ITEMS = `export const items = defineTable("items", {\n  id: id(),\n  title: text(),\n  createdAt: timestamp(),\n});\n`;

/** A schema module with exactly the helpers it uses imported (unused imports could fail lint). */
function schema(body: string): string {
  const all = ITEMS + body;
  const used = HELPERS.filter((h) => new RegExp(`\\b${h}\\(`).test(all));
  return `import { ${used.join(", ")} } from "${PKG}";\n\n${all}`;
}

function show(result: RunResult): string {
  return `exit ${String(result.code)}:\n${result.output.slice(-20_000)}`;
}

const apps: FixtureApp[] = [];
async function migApp(): Promise<FixtureApp> {
  const app = await FixtureApp.create({ layers: ["apps/base", "mig/base"] });
  apps.push(app);
  return app;
}

afterAll(async () => {
  for (const app of apps) await app.dispose();
});

describe("migration checker", () => {
  it(
    tag("CHECK-AC-004", "each supported change of MIG §2, generated by generate-migration one at a time, passes the checker"),
    async () => {
      const app = await migApp();
      const records = (extra: string, options = ""): string =>
        `export const records = defineTable("records", {\n  id: id(),\n  label: text(),\n  amount: integer().default(0),\n${extra}}${options});\n`;
      const tags = (options = ""): string => `export const tags = defineTable("tags", { id: id(), name: text() }${options});\n`;
      const steps: readonly [string, string][] = [
        ["add a table", records("") + tags()],
        ["add a nullable column", records("  note: text().nullable(),\n") + tags()],
        ["add a column with a static default", records("  note: text().nullable(),\n  active: boolean().default(true),\n") + tags()],
        ["add an index", records("  note: text().nullable(),\n  active: boolean().default(true),\n", ', { indexes: [["label"]] }') + tags()],
        ["add a unique constraint", records("  note: text().nullable(),\n  active: boolean().default(true),\n", ', { indexes: [["label"]] }') + tags(', { uniques: [["name"]] }')],
        ["drop an index", records("  note: text().nullable(),\n  active: boolean().default(true),\n") + tags(', { uniques: [["name"]] }')],
        ["drop a unique constraint", records("  note: text().nullable(),\n  active: boolean().default(true),\n") + tags()],
        ["drop a column", records("  active: boolean().default(true),\n") + tags()],
        ["drop a table", records("  active: boolean().default(true),\n")],
      ];
      for (const [change, body] of steps) {
        const before = { sqlite: (await migrationFiles(app, "sqlite")).length, postgres: (await migrationFiles(app, "postgres")).length };
        await app.write("src/server/schema.ts", schema(body));
        const gen = await app.cli(["generate-migration"]);
        expect(gen.code, `generate-migration for "${change}" ${show(gen)}`).toBe(0);
        expect((await migrationFiles(app, "sqlite")).length, `no new sqlite migration for "${change}"`).toBe(before.sqlite + 1);
        expect((await migrationFiles(app, "postgres")).length, `no new postgres migration for "${change}"`).toBe(before.postgres + 1);
      }
      const verify = await app.cli(["verify"]);
      expect(verify.code, show(verify)).toBe(0);
    },
    TIMEOUT,
  );

  it(
    tag("CHECK-AC-004", "mismatched dialect histories fail the checker (checksums updated, so only the schema comparison can catch it)"),
    async () => {
      const app = await migApp();
      const pg = await migrationFiles(app, "postgres");
      const last = pg[pg.length - 1];
      expect(last).toBeDefined();
      if (last === undefined) return;
      await editMigrationKeepingChecksum(app, last, (sql) => `${sql.trimEnd()}\n--> statement-breakpoint\nALTER TABLE "records" ADD COLUMN "extra" text;\n`);
      const verify = await app.cli(["verify"]);
      expect(verify.code, show(verify)).not.toBe(0);
      expect(verify.output, show(verify)).toMatch(/\bextra\b/);
    },
    TIMEOUT,
  );

  it(
    tag("CHECK-AC-004", "an edited applied migration fails the checker (checksum mismatch)"),
    async () => {
      const app = await migApp();
      const lite = await migrationFiles(app, "sqlite");
      const first = lite[0];
      expect(first).toBeDefined();
      if (first === undefined) return;
      await app.write(first, `${await app.read(first)}\n-- edited by hand after it was applied\n`);
      const verify = await app.cli(["verify"]);
      expect(verify.code, show(verify)).not.toBe(0);
      expect(verify.output, show(verify)).toContain(first.slice(first.lastIndexOf("/") + 1));
    },
    TIMEOUT,
  );

  const unsupported: readonly { change: string; slug: string; body: string; sqlite: string; postgres: string }[] = [
    {
      change: "a NOT NULL column without a static default added to an existing table",
      slug: "add_score",
      body: `export const records = defineTable("records", {\n  id: id(),\n  label: text(),\n  amount: integer().default(0),\n  score: integer(),\n});\n`,
      sqlite: "ALTER TABLE `records` ADD `score` integer NOT NULL;\n",
      postgres: 'ALTER TABLE "records" ADD COLUMN "score" integer NOT NULL;\n',
    },
    {
      change: "a column type change",
      slug: "amount_to_number",
      body: `export const records = defineTable("records", {\n  id: id(),\n  label: text(),\n  amount: number().default(0),\n});\n`,
      sqlite: [
        "CREATE TABLE `__new_records` (`id` text PRIMARY KEY NOT NULL, `label` text NOT NULL, `amount` real DEFAULT 0 NOT NULL);",
        "--> statement-breakpoint",
        'INSERT INTO `__new_records`("id", "label", "amount") SELECT "id", "label", "amount" FROM `records`;',
        "--> statement-breakpoint",
        "DROP TABLE `records`;",
        "--> statement-breakpoint",
        "ALTER TABLE `__new_records` RENAME TO `records`;",
        "",
      ].join("\n"),
      postgres: 'ALTER TABLE "records" ALTER COLUMN "amount" SET DATA TYPE double precision;\n',
    },
    {
      change: "a column rename",
      slug: "rename_label",
      body: `export const records = defineTable("records", {\n  id: id(),\n  title: text(),\n  amount: integer().default(0),\n});\n`,
      sqlite: "ALTER TABLE `records` RENAME COLUMN `label` TO `title`;\n",
      postgres: 'ALTER TABLE "records" RENAME COLUMN "label" TO "title";\n',
    },
  ];

  for (const u of unsupported) {
    it(
      tag("CHECK-AC-004", `${u.change} fails the checker with a diagnostic naming the add-copy-drop pattern`),
      async () => {
        const app = await migApp();
        await app.write("src/server/schema.ts", schema(u.body));
        await addHandWrittenMigration(app, "sqlite", u.slug, u.sqlite);
        await addHandWrittenMigration(app, "postgres", u.slug, u.postgres);
        const verify = await app.cli(["verify"]);
        expect(verify.code, show(verify)).not.toBe(0);
        expect(verify.output, show(verify)).toMatch(ADD_COPY_DROP);
      },
      TIMEOUT,
    );
  }
});
